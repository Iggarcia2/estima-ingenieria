const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const storage=new Map();
const ctx=vm.createContext({console,localStorage:{setItem(k,v){storage.set(k,v)},getItem(k){return storage.get(k)||null}},Intl,Date,Number,Math,Object,Array,Set,structuredClone});
for(const file of ['config.js','estimacion.js','interfaz.js'])vm.runInContext(fs.readFileSync(path.join(root,'js',file),'utf8'),ctx,{filename:file});
const library=JSON.parse(fs.readFileSync(path.join(root,'data/biblioteca_ratios.json'),'utf8'));
const published=JSON.parse(fs.readFileSync(path.join(root,'data/calibracion.json'),'utf8'));
vm.runInContext(`LIB=${JSON.stringify(library)};RATIOS=LIB.ratios;BY_ID=Object.fromEntries(RATIOS.map(r=>[r.id,r]));PUBLISHED_CALIBRATION=mergeCalibration(${JSON.stringify(published)});CALIBRATION=structuredClone(PUBLISHED_CALIBRATION);state=initialState();`,ctx);
const ev=str=>vm.runInContext(str,ctx);
let original=ev('calculate().total');assert.ok(original>0);
ev('CALIBRATION.physicalHH.concrete=0.5;persistCalibration()');const after=ev('calculate()');
assert.ok(after.total>original);
assert.ok(after.rows.some(r=>r.r.id==='FIS-concrete'));
assert.equal(after.rows.find(r=>r.r.id==='FIS-concrete').hh,100);
assert.equal(JSON.parse(storage.get('estimador_ingenieria_calibracion_v1')).physicalHH.concrete,0.5);
assert.ok(ev('renderCalibration(calculate()).includes("H/H físicas complementarias")'));
const beforeDriver=ev('quantityGuess(BY_ID["CIV-004"])');
ev('CALIBRATION.quantityDrivers.m3_por_plano_fundacion=35;persistCalibration()');
const afterDriver=ev('quantityGuess(BY_ID["CIV-004"])');
// Applies only when variable maps to n_planos_fundacion; the value is demonstrable directly:
assert.ok(ev("quantityGuess({variable_cantidad:'n_planos_fundacion'})")>=6);
assert.ok(afterDriver>=beforeDriver);
ev('CALIBRATION.rateOverrides["CIV-004"]=300');
const r=ev('calculate().rows.find(x=>x.r.id==="CIV-004")');
assert.ok(!r || r.rate===300);
ev('state.overrides["CIV-004"]={rate:71};');
const rr=ev('calculate().rows.find(x=>x.r.id==="CIV-004")');assert.ok(!rr||rr.rate===71);
ev('state.overrides={};CALIBRATION=mergeCalibration(JSON.parse(localStorage.getItem(CALIBRATION_KEY)));');
assert.equal(ev('CALIBRATION.physicalHH.concrete'),0.5);
assert.equal(ev('CALIBRATION.quantityDrivers.m3_por_plano_fundacion'),35);
console.log('✓ V4.3: H/H físicas adicionales, participación, cantidad inferida, persistencia y prioridades de ratios');
